    if not rows:
        no_hist.append((uid, phone, uname, curr_inst))
        continue

    his_insts = list(dict.fromkeys([r[0].strip() for r in rows]))
    # 判断当前机构是否在历史记录中出现过
    hit = any(h == curr_inst.strip() for h in his_insts)
    if hit:
        matched.append((uid, phone, uname, curr_inst, rows[0][1]))
